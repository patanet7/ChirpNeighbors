"""Generated arithmetic fixture only: explicit test review, not bird recognition."""

from __future__ import annotations

import tempfile
import unittest
from pathlib import Path

from app.audio_onnx.provider import ONNXProvider
from app.audio_onnx.technical_fixture import create_bundle
from app.audio_pipeline.contracts import AudioAnalyzeCommand, AudioCompletedEvent
from app.audio_pipeline.fixtures import FIXTURE_OWNER, FixtureStorage, fixture_command
from app.audio_pipeline.service import AudioService


class TechnicalMechanicsFixtureTests(unittest.TestCase):
    def test_authored_test_review_bundle_executes_without_claiming_a_bird(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "fixture"
            evidence = create_bundle(output)
            provider = ONNXProvider(output / "manifest.json")
            audio = (output / "synthetic-tone.wav").read_bytes()
            command = AudioAnalyzeCommand.model_validate(
                {
                    **fixture_command(audio).model_dump(),
                    "model": {
                        "providerId": "onnx-local",
                        "modelVersion": evidence["modelVersion"],
                        "taxonomyVersion": evidence["taxonomyVersion"],
                    },
                }
            )
            # Upload provenance intentionally remains recording, just like the
            # real intake route. These bytes were generated by this test above.
            storage = FixtureStorage(audio, synthetic_fixture=False)
            event = AudioService(storage, provider, provider.taxonomy).analyze(
                FIXTURE_OWNER, command
            )
            self.assertIsInstance(event, AudioCompletedEvent)
            if isinstance(event, AudioCompletedEvent):
                self.assertEqual(
                    event.provenance.licenseIdentifier,
                    "LicenseRef-Generated-Arithmetic-Fixture-Test-Only",
                )
                self.assertEqual(event.provenance.inputKind, "recording")
                self.assertEqual(len(event.reviewCandidates), 1)
                self.assertEqual(
                    event.reviewCandidates[0].scientificName,
                    "No biological identification",
                )
                self.assertGreater(event.rawCandidates[0].confidence, 0.8)
                self.assertIsNone(event.observedAt)
            self.assertIn(
                "ISOLATED TECHNICAL", (output / "FIXTURE-ONLY.txt").read_text()
            )

    def test_existing_files_and_symlink_directories_are_never_overwritten(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            output = Path(temporary) / "fixture"
            output.mkdir()
            saved = output / "existing.txt"
            saved.write_text("preserved")
            with self.assertRaises(ValueError):
                create_bundle(output)
            self.assertEqual(saved.read_text(), "preserved")
            link = Path(temporary) / "link"
            link.symlink_to(output)
            with self.assertRaises(ValueError):
                create_bundle(link)


if __name__ == "__main__":
    unittest.main()
