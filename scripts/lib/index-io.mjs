export function header() {
  return {
    id: '#',
    schema: INDEX_SCHEMA,
    about:
      'Every asset subject, slot and art file set. The id is the path: subject ["/" slot] ["/" version]; version vN = approved, c<sha8> = candidate. Generated by `node scripts/assets.mjs index`; checked by `node scripts/assets.mjs check`. Layout: docs/ASSETS.md.',
    rows: { subject: 'what the art is (tags live here)', slot: 'one place art can fill', art: 'one file set (frames) with its sha256s; files[].path is relative to the repo root', evidence: 'previews, contact sheets, GIFs and opaque renders: kept as evidence, never art' },
    kinds: KINDS,
    tags: TAGS,
  };
}

export function readIndex(file = INDEX) {
  if (!fs.existsSync(file)) return [];
  return fs
    .readFileSync(file, 'utf8')
    .split('\n')
    .filter((l) => l.trim())
    .map((l, i) => {
      try {
        return JSON.parse(l);
      } catch (err) {
        throw Error(`${file}:${i + 1}: ${err.message}`);
      }
    });
}

export function writeIndex(rows, file = INDEX) {
  const body = sortRows(rows.filter((r) => r.id !== '#'));
  const text = [header(), ...body].map(rowLine).join('\n') + '\n';
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text) return false;
  fs.writeFileSync(file, text);
  return true;
}
