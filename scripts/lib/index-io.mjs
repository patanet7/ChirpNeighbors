  cultivation: 'plants: wild | nursery | houseplant (houseplant implies setting: indoor)',
  setting: 'plants: yard | indoor',
  habit: 'plants: tree | shrub | grass | perennial | succulent | vine | groundcover',
  gives: 'objects, plants: food | water | perch | cover | light (multi); what a bird gets from it',
